# ── Layer isolation (mirrors import-linter contract, pure AST) ────────────────

@pytest.mark.fitness
def test_core_does_not_import_services_or_adapters():
    """core/ must not import from services or adapters.

    Enforced by import-linter in CI; this AST-based version catches the same
    violation without requiring the tool to be installed in the test runner.
    """
    forbidden_prefixes = ("services.", "adapters.")
    violations: list[str] = []

    for py_file in (ROOT / "core").rglob("*.py"):
        source = py_file.read_text(errors="replace")
        try:
            tree = ast.parse(source)
        except SyntaxError:
            continue
        # Only check module-level imports — lazy imports inside function bodies
        # are an intentional pattern for avoiding import cycles and are not a
        # layer violation (they don't create load-time coupling).
        for node in tree.body:
            if isinstance(node, ast.Import):
                for alias in node.names:
                    if any(alias.name.startswith(p) for p in forbidden_prefixes):
                        violations.append(f"{py_file.relative_to(ROOT)}:{node.lineno} imports {alias.name}")
            elif isinstance(node, ast.ImportFrom):
                module = node.module or ""
                if any(module.startswith(p.rstrip(".")) for p in forbidden_prefixes):
                    violations.append(f"{py_file.relative_to(ROOT)}:{node.lineno} from {module}")

    assert not violations, (
        "core/ must not import from services/ or adapters/ — "
        f"found {len(violations)} violation(s):\n" + "\n".join(violations)
    )


# ── API surface guard (OpenAPI snapshot) ─────────────────────────────────────

@pytest.mark.fitness
def test_openapi_snapshot_exists_and_has_routes():
    """The openapi.json snapshot (generated by make openapi) must exist and include core routes.

    Prevents accidental silent removal of endpoints. Regenerate the snapshot
    with `make openapi` after intentional API changes.
    """
    snapshot = ROOT / "governance" / "openapi.json"
    if not snapshot.exists():
        pytest.skip("openapi.json snapshot not yet generated — run `make openapi` to create it")

    data = json.loads(snapshot.read_text())
    paths = set(data.get("paths", {}).keys())

    required = {"/realms", "/connector-types", "/external-rags", "/corpus/ingest"}
    missing = required - {p for p in paths for r in required if p.startswith(r.rstrip("/{}"))}
    assert not missing, f"Required API paths missing from openapi snapshot: {missing}"


