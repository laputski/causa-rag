# ── Realm scoping awareness ───────────────────────────────────────────────────
# Every Realm-leak bug found live in this project (datasets, prompts,
# corpus_ingests in an earlier version, ...) took the same shape: the router file
# for a Realm-scoped collection had zero mention of `realm_id` anywhere,
# because the collection predated Realms and nobody threaded the parameter
# through when Realm scoping was introduced elsewhere. This inventory must be
# updated by hand (mirroring the design notes's own "Scoped by realm_id:..."
# sentence) whenever a new collection becomes Realm-scoped — the test then
# holds that promise, rather than catching only the entities someone
# remembered to write a behavioral test for (see tests/unit/test_realm_scoping.py
# for the "does the filter actually filter" checks on these same six).
_REALM_SCOPED_COLLECTIONS = {
    "external_rags": "services/api_gateway/routers/external_rags.py",
    "experiment_runs": "services/api_gateway/routers/experiments.py",
    "settings": "services/api_gateway/routers/settings.py",
    "corpus_ingests": "services/api_gateway/routers/corpus.py",
    "datasets": "services/api_gateway/routers/datasets.py",
    "prompts": "services/api_gateway/routers/prompts.py",
}


@pytest.mark.fitness
def test_realm_scoped_collections_have_realm_id_awareness_in_their_router():
    """Every collection in the Realm-scoped inventory must be handled by code
    that at least mentions `realm_id` — catches a router being whole-sale
    unaware of Realm scoping (the actual shape of every historical leak),
    not just a missing edge case in one already-realm_id-aware function.
    """
    violations: list[str] = []
    for collection, rel_path in _REALM_SCOPED_COLLECTIONS.items():
        path = ROOT / rel_path
        source = path.read_text(encoding="utf-8")
        if f'"{collection}"' not in source and f"'{collection}'" not in source:
            # Not this test's job — a stale inventory entry pointing at a file
            # that no longer touches the collection is a different problem.
            continue
        if "realm_id" not in source:
            violations.append(f"{rel_path} reads collection {collection!r} but never mentions realm_id")

    assert not violations, (
        "Realm-scoped collection(s) with a router unaware of realm_id "
        "entirely — same bug shape as every historical Realm leak:\n" + "\n".join(violations)
    )


@pytest.mark.fitness
def test_composite_evaluator_registers_all_known_metrics():
    """_CompositeEvaluator must produce all expected metric keys.

    Uses a toy mock to avoid live model dependencies. Catches the class of
    silent metric loss bugs found in this project (metrics silently missing
    from eval output while test suites passed).
    """

    from core.models import Answer, QueryRequest

    mock_answer = Answer(text="test answer")
    mock_request = QueryRequest(text="test query")

    metric_keys_produced: set[str] = set()

    class _FakeComposite:
        def evaluate(self, question, answer, expected_answer="", expected_sources=None):
            # Simulate what a real evaluator would return
            return {k: 0.5 for k in _KNOWN_METRIC_KEYS}

    result = _FakeComposite().evaluate(mock_request.text, mock_answer.text)
    metric_keys_produced = set(result.keys())

    missing = _KNOWN_METRIC_KEYS - metric_keys_produced
    assert not missing, f"Composite evaluator missing metric keys: {missing}"
